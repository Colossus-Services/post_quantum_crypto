// Downloads the official test vectors used by `test/vectors/` and trims them
// to a bounded subset that is committed to the repository.
//
// Usage: dart run tool/fetch_vectors.dart
//
// Every source URL and the SHA-256 of the downloaded file is recorded in
// test/vectors/PROVENANCE.md, so the trimmed files can be re-derived and
// audited.
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:pointycastle/export.dart' show SHA256Digest;

const _acvp =
    'https://raw.githubusercontent.com/usnistgov/ACVP-Server/master/gen-val/json-files';
const _wycheproof =
    'https://raw.githubusercontent.com/C2SP/wycheproof/main/testvectors_v1';
const _xwing =
    'https://raw.githubusercontent.com/dconnolly/draft-connolly-cfrg-xwing-kem/main/spec/test-vectors.json';
const _hpkePq =
    'https://raw.githubusercontent.com/hpkewg/hpke-pq/main/test-vectors.json';

final _outDir = Directory('test/vectors');
final _provenance = <String>[];

Future<void> main() async {
  _outDir.createSync(recursive: true);

  // NIST ACVP (FIPS 203 / FIPS 204). The internal projections carry both the
  // inputs and the expected outputs.
  await _acvpFile(
    'ML-KEM-keyGen-FIPS203',
    'acvp_mlkem_keygen.json',
    perGroup: 10,
  );
  await _acvpFile(
    'ML-KEM-encapDecap-FIPS203',
    'acvp_mlkem_encapdecap.json',
    perGroup: 10,
  );
  await _acvpFile(
    'ML-DSA-keyGen-FIPS204',
    'acvp_mldsa_keygen.json',
    perGroup: 10,
  );
  // Only the external/pure interface is exposed by this package.
  await _acvpFile(
    'ML-DSA-sigGen-FIPS204',
    'acvp_mldsa_siggen.json',
    perGroup: 6,
    groupFilter: (g) =>
        g['signatureInterface'] == 'external' && g['preHash'] == 'pure',
  );
  await _acvpFile(
    'ML-DSA-sigVer-FIPS204',
    'acvp_mldsa_sigver.json',
    perGroup: 15,
    groupFilter: (g) =>
        g['signatureInterface'] == 'external' && g['preHash'] == 'pure',
  );

  // FIPS 205: only the SHAKE parameter sets are exposed; external/pure only.
  // sigGen is limited to the hedged "f" sets ("s" signing is very slow in
  // pure Dart).
  await _acvpFile(
    'SLH-DSA-sigVer-FIPS205',
    'acvp_slhdsa_sigver.json',
    perGroup: 4,
    groupFilter: (g) =>
        '${g['parameterSet']}'.contains('SHAKE') &&
        g['signatureInterface'] == 'external' &&
        g['preHash'] == 'pure',
  );
  await _acvpFile(
    'SLH-DSA-sigGen-FIPS205',
    'acvp_slhdsa_siggen.json',
    perGroup: 2,
    groupFilter: (g) =>
        '${g['parameterSet']}'.contains('SHAKE') &&
        '${g['parameterSet']}'.endsWith('f') &&
        g['deterministic'] == false &&
        g['signatureInterface'] == 'external' &&
        g['preHash'] == 'pure',
  );

  // Wycheproof.
  await _wycheproofFile('hkdf_sha384_test.json');
  await _wycheproofFile('hkdf_sha256_test.json');
  await _wycheproofFile('hmac_sha384_test.json');
  await _wycheproofFile('hmac_sha256_test.json');
  await _wycheproofFile(
    'aes_gcm_test.json',
    groupFilter: (g) => g['keySize'] == 256 && g['ivSize'] == 96,
  );
  await _wycheproofFile('chacha20_poly1305_test.json');
  await _wycheproofFile('x25519_test.json');

  // Wycheproof ML-KEM (FIPS 203) and ML-DSA (FIPS 204). Their value is the
  // edge cases, so every non-valid test is kept; valid tests are trimmed per
  // group and flag combination (see _wycheproofPqcFile).
  for (final p in ['512', '768', '1024']) {
    await _wycheproofPqcFile('mlkem_${p}_test.json', validPerClass: 20);
    await _wycheproofPqcFile('mlkem_${p}_encaps_test.json', validPerClass: 10);
    await _wycheproofPqcFile(
      'mlkem_${p}_keygen_seed_test.json',
      validPerClass: 10,
    );
    await _wycheproofPqcFile('mlkem_${p}_semi_expanded_decaps_test.json');
  }
  for (final p in ['44', '65', '87']) {
    await _wycheproofPqcFile(
      'mldsa_${p}_sign_seed_test.json',
      validPerClass: 3,
    );
    await _wycheproofPqcFile(
      'mldsa_${p}_sign_noseed_test.json',
      validPerClass: 3,
    );
    await _wycheproofPqcFile('mldsa_${p}_verify_test.json', validPerClass: 3);
  }

  // RFC 9881 (ML-DSA) and RFC 9935 (ML-KEM) Appendix C example keys.
  await _rfcExamples(9881);
  await _rfcExamples(9935);

  // X-Wing draft and HPKE-PQ draft vectors (small; kept whole).
  await _copy(_xwing, 'xwing_draft.json');
  await _copy(_hpkePq, 'hpke_pq.json');

  File('${_outDir.path}/PROVENANCE.md').writeAsStringSync(
    [
      '# Test-vector provenance',
      '',
      'Generated by `dart run tool/fetch_vectors.dart`. Files are trimmed '
          'subsets of the upstream sources below; the SHA-256 is of the full '
          'upstream file at download time.',
      '',
      '- NIST ACVP: the first N tests per group.',
      '- Wycheproof ML-KEM / ML-DSA (`wycheproof_mlkem_*`, `wycheproof_mldsa_*`): '
          'every test whose result is not `valid` is kept; valid tests are kept '
          'up to N per (group, flag set), so every kind of edge case is '
          'represented. The semi-expanded decapsulation sets are kept whole.',
      '- RFC examples (`rfc*_examples.json`): every PEM block of Appendix C, '
          'with its section number and label, decoded to DER (hex). C.3 '
          'certificates are included but not used (this package has no X.509 '
          'certificate parser).',
      '- Not used: RFC 9909 (SLH-DSA in X.509), whose only example is '
          'SLH-DSA-SHA2-128s; this package implements the SHAKE parameter '
          'sets only.',
      '',
      '| File | Source | Upstream SHA-256 |',
      '|---|---|---|',
      ..._provenance,
      '',
    ].join('\n'),
  );
  stdout.writeln('Vectors written to ${_outDir.path}');
}

Future<(String, String)> _download(String url) async {
  final client = HttpClient();
  try {
    final req = await client.getUrl(Uri.parse(url));
    final res = await req.close();
    if (res.statusCode != 200) {
      throw StateError('GET $url -> ${res.statusCode}');
    }
    final bytes = await res.fold<List<int>>([], (a, b) => a..addAll(b));
    final digest = SHA256Digest().process(Uint8List.fromList(bytes));
    final hex = digest.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
    return (utf8.decode(bytes), hex);
  } finally {
    client.close();
  }
}

Future<void> _acvpFile(
  String dir,
  String out, {
  required int perGroup,
  bool Function(Map<String, dynamic>)? groupFilter,
}) async {
  final url = '$_acvp/$dir/internalProjection.json';
  final (text, sha) = await _download(url);
  final json = jsonDecode(text) as Map<String, dynamic>;
  final groups = [
    for (final g in (json['testGroups'] as List).cast<Map<String, dynamic>>())
      if (groupFilter == null || groupFilter(g))
        {...g, 'tests': (g['tests'] as List).take(perGroup).toList()},
  ];
  _write(out, {...json, 'testGroups': groups});
  _provenance.add('| `$out` | $url | `$sha` |');
}

Future<void> _wycheproofFile(
  String name, {
  bool Function(Map<String, dynamic>)? groupFilter,
}) async {
  final url = '$_wycheproof/$name';
  final (text, sha) = await _download(url);
  final json = jsonDecode(text) as Map<String, dynamic>;
  final groups = [
    for (final g in (json['testGroups'] as List).cast<Map<String, dynamic>>())
      if (groupFilter == null || groupFilter(g)) g,
  ];
  _write('wycheproof_$name', {...json, 'testGroups': groups});
  _provenance.add('| `wycheproof_$name` | $url | `$sha` |');
}

/// A Wycheproof PQC file: all tests whose result is not `valid` are kept;
/// valid tests are kept up to [validPerClass] per (group, flag set), or all
/// of them when [validPerClass] is null.
Future<void> _wycheproofPqcFile(String name, {int? validPerClass}) async {
  final url = '$_wycheproof/$name';
  final (text, sha) = await _download(url);
  final json = jsonDecode(text) as Map<String, dynamic>;
  final groups = <Map<String, dynamic>>[];
  for (final g in (json['testGroups'] as List).cast<Map<String, dynamic>>()) {
    final seen = <String, int>{};
    final tests = [
      for (final t in (g['tests'] as List).cast<Map<String, dynamic>>())
        if (t['result'] != 'valid' ||
            validPerClass == null ||
            _countClass(seen, t) <= validPerClass)
          t,
    ];
    groups.add({...g, 'tests': tests});
  }
  _write('wycheproof_$name', {...json, 'testGroups': groups});
  _provenance.add('| `wycheproof_$name` | $url | `$sha` |');
}

/// Counts [t] in its flag-set class and returns the new count.
int _countClass(Map<String, int> seen, Map<String, dynamic> t) {
  final flags = [...((t['flags'] as List?) ?? const [])]..sort();
  final key = flags.join(',');
  return seen[key] = (seen[key] ?? 0) + 1;
}

/// Extracts every PEM block of an RFC's Appendix C, with its section.
Future<void> _rfcExamples(int rfc) async {
  final url = 'https://www.rfc-editor.org/rfc/rfc$rfc.txt';
  final (text, sha) = await _download(url);
  final heading = RegExp(r'^(C\.[0-9.]*[0-9])\.?\s+(.*)$');
  final begin = RegExp(r'^\s*-----BEGIN ([A-Z ]+)-----\s*$');
  final end = RegExp(r'^\s*-----END ([A-Z ]+)-----\s*$');
  final base64Line = RegExp(r'^\s*([A-Za-z0-9+/=]+)\s*$');
  final examples = <Map<String, Object>>[];
  var inAppendixC = false;
  String? section;
  String? title;
  String? label;
  StringBuffer? body;
  for (final line in const LineSplitter().convert(text)) {
    if (line.startsWith('Appendix C.')) inAppendixC = true;
    if (!inAppendixC) continue;
    final h = heading.firstMatch(line);
    if (h != null) {
      section = h.group(1);
      title = h.group(2)!.trim();
      continue;
    }
    final b = begin.firstMatch(line);
    if (b != null) {
      label = b.group(1);
      body = StringBuffer();
      continue;
    }
    if (body == null) continue;
    if (end.hasMatch(line)) {
      examples.add({
        'section': section!,
        'title': title!,
        'index': examples.where((e) => e['section'] == section).length,
        'label': label!,
        'der': base64
            .decode(body.toString())
            .map((b) => b.toRadixString(16).padLeft(2, '0'))
            .join(),
      });
      body = null;
      continue;
    }
    final l = base64Line.firstMatch(line);
    if (l == null) throw StateError('RFC $rfc: unexpected line in PEM: $line');
    body.write(l.group(1));
  }
  final out = 'rfc${rfc}_examples.json';
  _write(out, {
    'source': url,
    'description': 'Appendix C PEM examples of RFC $rfc, decoded to DER.',
    'examples': examples,
  });
  _provenance.add('| `$out` | $url | `$sha` |');
}

Future<void> _copy(String url, String out) async {
  final (text, sha) = await _download(url);
  _write(out, jsonDecode(text) as Object);
  _provenance.add('| `$out` | $url | `$sha` |');
}

void _write(String name, Object json) {
  File(
    '${_outDir.path}/$name',
  ).writeAsStringSync(const JsonEncoder.withIndent(' ').convert(json));
}
